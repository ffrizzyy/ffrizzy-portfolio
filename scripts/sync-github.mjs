// Refresh the committed GitHub snapshot used as the offline fallback.
//
// The site reads live repository metadata at request time (see
// src/lib/github.server.ts) and revalidates it once a day. When the API is
// unreachable, rate limited, or not configured, the build and the Open source
// section fall back to the file this script writes. Curated copy lives in
// src/content/repos.ts, so re-running this script never overwrites a rewritten
// description or a case-study link.
//
// Usage:
//   pnpm sync:repos
//   GITHUB_TOKEN=... pnpm sync:repos   # raises the rate limit from 60 to 5,000/hr

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const USERNAME = process.env.GITHUB_USERNAME ?? "ffrizzyy";
const TOKEN = process.env.GITHUB_TOKEN;
const OUT = join(ROOT, "src", "content", "repos.snapshot.ts");

function cleanDescription(value) {
  if (!value) return "A public repository on GitHub";
  return value
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&#39;/g, "'")
    .replace(/&quot;/g, '"')
    // Spec 2.10 bans em-dashes and en-dashes in source copy, and the snapshot is
    // source, so normalise them before this can fail `pnpm check:copy`.
    .replace(/[\u2014\u2013]/g, "-")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\.$/, "");
}

function cleanUrl(value) {
  if (typeof value !== "string") return undefined;
  const trimmed = value.trim();
  return /^https?:\/\//i.test(trimmed) ? trimmed : undefined;
}

const headers = {
  Accept: "application/vnd.github+json",
  "User-Agent": "ffrizzy-portfolio-sync",
  "X-GitHub-Api-Version": "2022-11-28",
};
if (TOKEN) headers.Authorization = `Bearer ${TOKEN}`;

const response = await fetch(
  `https://api.github.com/users/${encodeURIComponent(USERNAME)}/repos?per_page=100&sort=updated`,
  { headers },
);

if (!response.ok) {
  console.error(`GitHub answered ${response.status} ${response.statusText}`);
  console.error("No snapshot was written. The existing file is unchanged.");
  process.exit(1);
}

const payload = await response.json();
if (!Array.isArray(payload)) {
  console.error("GitHub did not return a repository array. No snapshot was written.");
  process.exit(1);
}

const repos = payload
  .map((repo) => ({
    name: repo.name,
    description: cleanDescription(repo.description),
    url: repo.html_url,
    ...(repo.language ? { language: repo.language } : {}),
    ...(cleanUrl(repo.homepage) ? { homepage: cleanUrl(repo.homepage) } : {}),
    stars: repo.stargazers_count ?? 0,
    forks: repo.forks_count ?? 0,
    openIssues: repo.open_issues_count ?? 0,
    topics: Array.isArray(repo.topics) ? repo.topics : [],
    ...(repo.pushed_at ? { pushedAt: repo.pushed_at } : {}),
    ...(repo.created_at ? { createdAt: repo.created_at } : {}),
    archived: Boolean(repo.archived),
    fork: Boolean(repo.fork),
    ...(repo.license?.spdx_id ? { license: repo.license.spdx_id } : {}),
  }))
  .sort((a, b) => {
    const byPush = (b.pushedAt ?? "").localeCompare(a.pushedAt ?? "");
    return byPush === 0 ? a.name.localeCompare(b.name) : byPush;
  });

const file = `// Generated by scripts/sync-github.mjs. Do not edit by hand.
//
// The committed fallback for the Open source section. The daily fetch in
// src/lib/github.server.ts replaces this when the GitHub API answers. Curated
// descriptions, topics, and case-study links live in src/content/repos.ts and
// are applied over this snapshot at read time, so re-running the sync cannot
// overwrite editorial copy.

import type { Repo } from "./schema";

export const repoSnapshot: Repo[] = ${JSON.stringify(repos, null, 2)};
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, file, "utf8");
console.log(`Wrote ${repos.length} repositories to ${OUT}`);
