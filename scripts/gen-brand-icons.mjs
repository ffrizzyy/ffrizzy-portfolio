// Generates src/lib/brand-icons.ts.
//
// The tools strip is mostly simple-icons marks, but a few brands the owner
// asked for are not in the installed simple-icons set: Microsoft Excel, Adobe
// Photoshop, Visual Studio Code, and OpenAI (ChatGPT). Spec 1.1 says to drop a
// missing brand rather than hand-draw it, so these are copied from public icon
// sets byte for byte instead of being drawn here, and this script is kept as
// the record of where each one came from.
//
// Run manually:
//   node scripts/gen-brand-icons.mjs
//
// The output is committed, so the build never depends on a network request.

import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * `glyph` picks which <path> of the source to keep. Adobe Photoshop ships as a
 * filled rounded square plus a separate "Ps" glyph; the square would render as
 * a solid block at 32px, so only the glyph is kept and the mark stays legible
 * in one colour like the rest of the strip.
 */
const SOURCES = [
  {
    key: "excel",
    name: "Microsoft Excel",
    url: "https://api.iconify.design/mdi/microsoft-excel.svg",
    source: "MDI (Apache 2.0)",
    glyph: 0,
  },
  {
    key: "vscode",
    name: "Visual Studio Code",
    url: "https://api.iconify.design/mdi/microsoft-visual-studio-code.svg",
    source: "MDI (Apache 2.0)",
    glyph: 0,
  },
  {
    key: "photoshop",
    name: "Adobe Photoshop",
    url: "https://api.iconify.design/logos/adobe-photoshop.svg",
    source: "SVG Logos (CC0)",
    glyph: 0,
  },
  {
    key: "chatgpt",
    name: "ChatGPT",
    url: "https://api.iconify.design/logos/openai-icon.svg",
    source: "SVG Logos (CC0)",
    glyph: 0,
  },
];

async function collect(source) {
  const response = await fetch(source.url);
  if (!response.ok) throw new Error(`${source.url} -> HTTP ${response.status}`);
  const svg = await response.text();

  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  if (!viewBox) throw new Error(`${source.url} has no viewBox`);

  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((match) => match[1]);
  if (paths.length === 0) throw new Error(`${source.url} has no <path>`);

  const path = paths[source.glyph];
  if (!path) throw new Error(`${source.url} has no path at index ${source.glyph}`);

  return { viewBox, path };
}

function render(entries) {
  const body = entries
    .map(
      (entry) =>
        `  // ${entry.source}\n` +
        `  ${entry.key}: {\n` +
        `    title: ${JSON.stringify(entry.name)},\n` +
        `    viewBox: ${JSON.stringify(entry.viewBox)},\n` +
        `    path: ${JSON.stringify(entry.path)},\n` +
        `  },`,
    )
    .join("\n");

  return `/**
 * Brand marks the tools strip needs that are not in the installed simple-icons
 * set.
 *
 * Generated by scripts/gen-brand-icons.mjs, not written by hand. The path and
 * the viewBox for each mark are copied from a public icon set, so nothing here
 * is drawn: spec 1.1's rule that a missing brand is dropped rather than drawn
 * is kept, and the brand is simply sourced from somewhere that already carries
 * it. Each mark renders in currentColor like the simple-icons ones, so the
 * strip stays one visual family.
 *
 * Do not edit by hand. Re-run the script instead.
 */

export type BrandMark = { title: string; viewBox: string; path: string };

export const EXTRA_BRAND_ICONS: Record<string, BrandMark> = {
${body}
};
`;
}

const entries = [];
for (const source of SOURCES) {
  const { viewBox, path } = await collect(source);
  entries.push({ ...source, viewBox, path });
}

await writeFile(join(ROOT, "src", "lib", "brand-icons.ts"), render(entries), "utf8");
console.log(`Wrote src/lib/brand-icons.ts with ${entries.length} brand marks.`);
